package wasm

import (
	"context"
	"os"
	"path/filepath"
	"testing"
)

func TestEjecutorWASM(t *testing.T) {
	bin := []byte{
		0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
		0x01, 0x05, 0x01, 0x60, 0x00, 0x01, 0x7f,
		0x03, 0x02, 0x01, 0x00,
		0x07, 0x0e, 0x01, 0x0a,
		0x61, 0x6c, 0x73, 0x65, 0x74, 0x5f, 0x6d, 0x61, 0x69, 0x6e,
		0x00, 0x00,
		0x0a, 0x06, 0x01, 0x04, 0x00, 0x41, 0x2a, 0x0b,
	}
	ruta := filepath.Join(t.TempDir(), "gene.wasm")
	if err := os.WriteFile(ruta, bin, 0600); err != nil {
		t.Fatal(err)
	}
	valor, err := Nuevo().Ejecutar(context.Background(), ruta, "alset_main")
	if err != nil {
		t.Fatal(err)
	}
	if valor != 42 {
		t.Fatalf("resultado WASM: %d", valor)
	}
}
