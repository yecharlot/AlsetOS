package declarativo

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// GenerarCodigo escribe artefactos Go derivados del manifiesto de reglas.
// El código es RESULTADO de la plataforma, no la fuente de verdad.
// El usuario PUEDE editarlo después; la fuente canónica sigue siendo el JSON de reglas.
func GenerarCodigo(m *ManifiestoReglas, dir string) error {
	if m == nil {
		return fmt.Errorf("manifiesto nulo")
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	pkg := sanitizeIdent(m.App)
	if pkg == "" {
		pkg = "appgenerada"
	}

	var b strings.Builder
	b.WriteString("// Code generated by AlsetOS plataforma from rules. DO NOT treat as source of truth.\n")
	b.WriteString("// Fuente canónica: manifiesto de reglas JSON. Puedes ajustar a mano con cuidado.\n")
	b.WriteString("//go:generate echo reglas-primero\n\n")
	b.WriteString("package " + pkg + "\n\n")
	b.WriteString("import \"github.com/yecharlot/AlsetOS/declarativo\"\n\n")
	b.WriteString("// AppName nombre de la aplicación generada.\n")
	b.WriteString(fmt.Sprintf("const AppName = %q\n", m.App))
	b.WriteString(fmt.Sprintf("const AppVersion = %q\n\n", m.Version))
	b.WriteString("// Organismos devuelve las declaraciones generadas desde reglas.\n")
	b.WriteString("func Organismos() []declarativo.OrgDecl {\n")
	b.WriteString("\treturn []declarativo.OrgDecl{\n")
	for _, o := range m.Organismos {
		b.WriteString("\t\t{\n")
		b.WriteString(fmt.Sprintf("\t\t\tOID: %q, Name: %q, Version: %q, Kind: %q,\n", o.OID, o.Name, o.Version, o.Kind))
		if o.Description != "" {
			b.WriteString(fmt.Sprintf("\t\t\tDescription: %q,\n", o.Description))
		}
		if len(o.Capabilities) > 0 {
			b.WriteString("\t\t\tCapabilities: []string{")
			for i, c := range o.Capabilities {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(fmt.Sprintf("%q", c))
			}
			b.WriteString("},\n")
		}
		if len(o.Goals) > 0 {
			b.WriteString("\t\t\tGoals: []string{")
			for i, g := range o.Goals {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(fmt.Sprintf("%q", g))
			}
			b.WriteString("},\n")
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t}\n}\n")

	out := filepath.Join(dir, "organismos_gen.go")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		return err
	}

	readme := fmt.Sprintf(`# Código generado — %s

Este directorio lo produjo **AlsetOS plataforma** a partir de reglas.

- Fuente de verdad: el manifiesto JSON de reglas (no este Go).
- Puedes modificar el Go para matices; al re-aplicar reglas se regenera.
- Runtime: declarativo.Runtime.AplicarReglas / LoadAssembly.

App: %s
Versión: %s
`, m.App, m.App, m.Version)
	return os.WriteFile(filepath.Join(dir, "README.md"), []byte(readme), 0o644)
}

func sanitizeIdent(s string) string {
	var b strings.Builder
	for i, r := range strings.ToLower(s) {
		if r >= 'a' && r <= 'z' || (i > 0 && r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else if r == '-' || r == '_' || r == ' ' {
			// skip
		}
	}
	out := b.String()
	if out == "" || (out[0] >= '0' && out[0] <= '9') {
		return "appgenerada"
	}
	return out
}
